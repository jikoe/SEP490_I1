using AgriSustain.Api;
using AgriSustain.Api.Middlewares;
using AgriSustain.Api.Security.Authentication;
using AgriSustain.Application.Interfaces.Identity;
using AgriSustain.Infrastructure;
using AgriSustain.Infrastructure.Data.Contexts;
using Microsoft.AspNetCore.Authentication;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.FileProviders;
using Microsoft.OpenApi.Models;

var builder = WebApplication.CreateBuilder(args);

if (builder.Environment.IsDevelopment())
{
    // Machine-local connection override for a verified running LocalDB pipe. It is ignored by
    // Git and generated by tools/use-running-localdb.ps1; never commit a transient pipe name.
    // Explicit environment/CLI settings keep precedence over the optional local JSON file.
    builder.Configuration.AddJsonFile("appsettings.Local.json", optional: true, reloadOnChange: true)
        .AddEnvironmentVariables().AddCommandLine(args);
}

builder.Services.AddControllers();
// Database First: the generated context has no connection string or OnConfiguring override.
// Resolve configuration from DI so isolated test hosts can replace the exact SQL connection.
builder.Services.AddDbContext<AgriSustainDbContext>((provider, options) =>
    options.UseSqlServer(provider.GetRequiredService<IConfiguration>()
        .GetConnectionString("AgriSustain")
        ?? throw new InvalidOperationException("Missing ConnectionStrings:AgriSustain.")));
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new OpenApiInfo { Title = "AgriSustain — Three UCs", Version = "v1" });
    // MOCK-AUTH: Swagger's Authorize box accepts 'Demo admin' or 'Demo retail-customer'.
    // This local review selector must be replaced by the team's real authentication scheme.
    options.AddSecurityDefinition("LocalReview", new OpenApiSecurityScheme
    {
        Type = SecuritySchemeType.ApiKey, In = ParameterLocation.Header, Name = "Authorization",
        Description = "Development only: Demo admin / Demo retail-customer"
    });
    options.AddSecurityRequirement(new OpenApiSecurityRequirement
    {
        [new OpenApiSecurityScheme { Reference = new OpenApiReference
            { Type = ReferenceType.SecurityScheme, Id = "LocalReview" } }] = Array.Empty<string>()
    });
});
builder.Services.AddApplication();
builder.Services.AddInfrastructure(builder.Configuration, builder.Environment.IsDevelopment());
builder.Services.AddHttpContextAccessor();
builder.Services.AddScoped<ICurrentUser, HttpCurrentUser>();
builder.Services.AddAuthentication("Demo")
    .AddScheme<AuthenticationSchemeOptions, DemoAuthenticationHandler>("Demo", _ => { });
builder.Services.AddAuthorization(options =>
{
    // DEMO-PERMISSIONS: only SystemAdmin is mapped here. CustomerSupport and other staff
    // permissions are not approved yet; do not grant them every Administration action.
    options.AddPolicy("Administration", policy => policy.RequireRole("SystemAdmin"));
    options.AddPolicy("RetailCustomerCheckout", policy => policy.RequireRole("RetailCustomer"));
});
builder.Services.AddExceptionHandler<ApiExceptionHandler>();
builder.Services.AddProblemDetails();

var app = builder.Build();

app.UseExceptionHandler();
if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}
// Keep framework-generated authentication/authorization failures in the same sanitized
// ProblemDetails shape as use-case failures, with a trace ID for the team to diagnose.
app.UseStatusCodePages(async statusContext =>
{
    var context = statusContext.HttpContext;
    await context.Response.WriteAsJsonAsync(new Microsoft.AspNetCore.Mvc.ProblemDetails
    {
        Status = context.Response.StatusCode,
        Title = context.Response.StatusCode == 401 ? "Phiên không hợp lệ hoặc đã bị thu hồi."
            : "Không thể truy cập tài nguyên hoặc thực hiện thao tác.",
        Extensions = { ["code"] = $"HTTP_{context.Response.StatusCode}",
            ["traceId"] = context.TraceIdentifier }
    });
});
string frontendPath = Path.GetFullPath(Path.Combine(
    app.Environment.ContentRootPath, "../../frontend/dist"));
if (Directory.Exists(frontendPath))
{
    // Optional local build output. Run frontend/npm build once to use only the API host.
    var frontendFiles = new PhysicalFileProvider(frontendPath);
    app.Lifetime.ApplicationStopped.Register(frontendFiles.Dispose);
    app.UseDefaultFiles(new DefaultFilesOptions { FileProvider = frontendFiles });
    app.UseStaticFiles(new StaticFileOptions { FileProvider = frontendFiles });
}
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();
// Liveness/configuration only: not a SQL connectivity or external-provider readiness assertion.
app.MapGet("/health", () => Results.Ok(new
{
    status = "healthy", service = "AgriSustain.Api",
    persistence = app.Configuration["Persistence:Mode"] ?? "InMemory"
}));
// Readiness is separate from liveness: actually opens SQL and reads one mapped business table.
// No entity data, password hashes or connection strings are returned by this endpoint.
app.MapGet("/health/database", async (AgriSustainDbContext db, CancellationToken cancellationToken) =>
{
    if (!await db.Database.CanConnectAsync(cancellationToken))
    {
        return Results.Problem("Không kết nối được SQL Server.", statusCode: 503);
    }
    await db.Category.AsNoTracking().Select(row => row.CategoryId).Take(1)
        .ToArrayAsync(cancellationToken);
    return Results.Ok(new
    {
        connected = true, provider = db.Database.ProviderName,
        database = db.Database.GetDbConnection().Database,
        mappedEntities = db.Model.GetEntityTypes().Count()
    });
});

app.Run();

public partial class Program;
